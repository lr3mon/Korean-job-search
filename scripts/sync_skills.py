def _no_symlink(root: Path, relative: Path) -> None:
    """Refuse redirecting any owned path through a symlink."""
    current = root
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            raise ValueError(f"symlink is not allowed: {current.relative_to(root).as_posix()}")


def _files(root: Path, relative: Path) -> dict[Path, bytes]:
    _no_symlink(root, relative)
    directory = root / relative
    if not directory.exists():
        return {}
    if not directory.is_dir():
        raise ValueError(f"expected directory: {relative.as_posix()}")
    result = {}
    for folder, dirs, names in os.walk(directory, followlinks=False):
        for name in sorted(dirs + names):
            path = Path(folder) / name
            _no_symlink(root, path.relative_to(root))
            if path.is_file():
                result[path.relative_to(directory)] = path.read_bytes()
            elif not path.is_dir():
                raise ValueError(f"non-regular file: {path.relative_to(root).as_posix()}")
    return result


def _atomic_write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".sync-", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def synchronize(root: Path, *, check: bool = False) -> list[str]:
    """Return remaining problems; generate only known paths when not checking.

    Validate ALL destinations before writes so a symlink/unknown file cannot
    cause partial synchronization. Use portable ordinary files for Windows.
    """
    root = Path(root).resolve()
    source = _files(root, CANONICAL)
    if Path("SKILL.md") not in source:
        raise ValueError("canonical SKILL.md is missing")
    expected: dict[Path, bytes] = {}
    blockers = []
    for destination in DESTINATIONS:
        actual = _files(root, destination)
        for extra in sorted(set(actual) - set(source)):
            blockers.append(f"unexpected: {(destination / extra).as_posix()} (preserved; review manually)")
        for relative, content in source.items():
            expected[destination / relative] = content
    for name, text in POINTERS.items():
        expected[Path(name)] = text.encode("utf-8")
    for relative in expected:
        _no_symlink(root, relative)
        path = root / relative
        if path.exists() and not path.is_file():
            raise ValueError(f"expected regular file: {relative.as_posix()}")
    if blockers:
        return blockers
    issues = []
    for relative, content in sorted(expected.items()):
        path = root / relative
        existing = path.read_bytes() if path.is_file() else None
        # Git may check generated root text out as CRLF on Windows. The
        # bundle itself is copied byte-for-byte from the checked-out source.
        compared = existing
        if relative.as_posix() in POINTERS and existing is not None:
            compared = existing.replace(b"\r\n", b"\n")
        if compared == content:
            continue
        if check:
            label = "missing" if existing is None else "stale"
            issues.append(f"{label}: {relative.as_posix()}")
        else:
            _atomic_write(path, content)
    return issues


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    try:
        issues = synchronize(root, check=args.check)
    except (OSError, ValueError) as exc:
        print(f"adapter error: {exc}", file=sys.stderr)
        return 2
    if issues:
        for issue in issues:
            print(issue)
        return 1
    print("Adapters synchronized; canonical bundle and entrypoints match.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
